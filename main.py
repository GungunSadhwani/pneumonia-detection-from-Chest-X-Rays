import argparse
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import tensorflow as tf
from sklearn.metrics import (ConfusionMatrixDisplay, RocCurveDisplay,
                             classification_report, confusion_matrix, roc_auc_score)
from tensorflow.keras import layers, models

# ----------------------------- config -----------------------------
KAGGLE_HANDLE = "paultimothymooney/chest-xray-pneumonia"
CLASS_NAMES = ["NORMAL", "PNEUMONIA"]  # label 0 = NORMAL, 1 = PNEUMONIA
IMG_SIZE = (224, 224)
BATCH_SIZE = 32
SEED = 42
VAL_SPLIT = 0.2
EPOCHS = 20
FINE_TUNE_EPOCHS = 10
LR = 1e-3
FINE_TUNE_LR = 1e-5
FINE_TUNE_AT = 100  # MobileNetV2 layers below this index stay frozen

try:
    ROOT = Path(__file__).resolve().parent
except NameError:  # running inside a notebook (Colab / Jupyter): no __file__
    ROOT = Path.cwd()
MODELS_DIR = ROOT / "models"
RESULTS_DIR = ROOT / "results"
MODELS_DIR.mkdir(exist_ok=True)
RESULTS_DIR.mkdir(exist_ok=True)


# ----------------------------- data -----------------------------
def get_data_root(data_dir=None):
    """Return the folder containing train/ and test/. Downloads from Kaggle if needed."""
    if data_dir is None:
        import kagglehub  # downloads once, then re-uses kagglehub's local cache

        print(f"Fetching dataset '{KAGGLE_HANDLE}' from Kaggle (about 1.2 GB the first time)...")
        data_dir = kagglehub.dataset_download(KAGGLE_HANDLE)
    base = Path(data_dir)
    for p in [base, *[q for q in base.rglob("*") if q.is_dir() and "__MACOSX" not in q.parts]]:
        if (p / "train").is_dir() and (p / "test").is_dir():
            return p
    raise FileNotFoundError(f"No train/ and test/ folders found under {base}")


def get_datasets(root):
    def load(path, **kw):
        return tf.keras.utils.image_dataset_from_directory(
            path, labels="inferred", label_mode="binary", class_names=CLASS_NAMES,
            color_mode="rgb", image_size=IMG_SIZE, batch_size=BATCH_SIZE, **kw)

    split = dict(shuffle=True, seed=SEED, validation_split=VAL_SPLIT)
    train_ds = load(root / "train", subset="training", **split)
    val_ds = load(root / "train", subset="validation", **split)
    test_ds = load(root / "test", shuffle=False)
    auto = tf.data.AUTOTUNE
    return train_ds.prefetch(auto), val_ds.cache().prefetch(auto), test_ds.cache().prefetch(auto)


def class_weights(train_ds):
    counts = np.zeros(2)
    for _, y in train_ds:
        counts += np.bincount(y.numpy().astype(int).ravel(), minlength=2)
    return {i: counts.sum() / (2 * c) for i, c in enumerate(counts)}, counts


# ----------------------------- models -----------------------------
def augmentation():
    # Mild only: flips / heavy rotation are unrealistic for chest X-rays.
    return tf.keras.Sequential([layers.RandomRotation(0.05), layers.RandomZoom(0.1),
                                layers.RandomTranslation(0.05, 0.05),
                                layers.RandomContrast(0.1)], name="augmentation")


def build_cnn():
    inp = layers.Input(shape=(*IMG_SIZE, 3))
    x = layers.Rescaling(1 / 255)(augmentation()(inp))
    for f in (32, 64, 128, 256):
        x = layers.Conv2D(f, 3, padding="same", activation="relu")(x)
        x = layers.BatchNormalization()(x)
        x = layers.MaxPooling2D()(x)
    x = layers.GlobalAveragePooling2D()(x)
    x = layers.Dropout(0.5)(layers.Dense(128, activation="relu")(x))
    return models.Model(inp, layers.Dense(1, activation="sigmoid")(x), name="simple_cnn"), None


def build_mobilenet():
    base = tf.keras.applications.MobileNetV2(input_shape=(*IMG_SIZE, 3), include_top=False,
                                             weights="imagenet")
    base.trainable = False
    inp = layers.Input(shape=(*IMG_SIZE, 3))
    x = tf.keras.applications.mobilenet_v2.preprocess_input(augmentation()(inp))
    x = layers.GlobalAveragePooling2D()(base(x, training=False))
    x = layers.Dropout(0.3)(x)
    return models.Model(inp, layers.Dense(1, activation="sigmoid")(x), name="mobilenetv2"), base


def compile_model(model, lr):
    model.compile(optimizer=tf.keras.optimizers.Adam(lr), loss="binary_crossentropy",
                  metrics=["accuracy", tf.keras.metrics.Precision(name="precision"),
                           tf.keras.metrics.Recall(name="recall"),
                           tf.keras.metrics.AUC(name="auc")])
    return model


# ----------------------------- train -----------------------------
def cmd_train(args):
    tf.keras.utils.set_random_seed(SEED)
    train_ds, val_ds, _ = get_datasets(get_data_root(args.data_dir))
    weights, counts = class_weights(train_ds)
    print(f"Train counts {dict(zip(CLASS_NAMES, counts.astype(int)))}, class weights {weights}")
    path = str(MODELS_DIR / f"{args.model}_best.keras")

    def callbacks():
        return [tf.keras.callbacks.ModelCheckpoint(path, monitor="val_auc", mode="max",
                                                   save_best_only=True),
                tf.keras.callbacks.EarlyStopping(monitor="val_auc", mode="max", patience=5,
                                                 restore_best_weights=True),
                tf.keras.callbacks.ReduceLROnPlateau(monitor="val_loss", factor=0.3,
                                                     patience=2, min_lr=1e-7)]

    def fit(model, epochs):
        return model.fit(train_ds, validation_data=val_ds, epochs=epochs,
                         class_weight=weights, callbacks=callbacks()).history

    model, base = build_cnn() if args.model == "cnn" else build_mobilenet()
    model = compile_model(model, LR)
    history = fit(model, args.epochs)

    if base is not None and not args.no_fine_tune and args.fine_tune_epochs > 0:
        print("--- Fine-tuning top MobileNetV2 layers ---")
        base.trainable = True
        for layer in base.layers[:FINE_TUNE_AT]:
            layer.trainable = False
        model = compile_model(model, FINE_TUNE_LR)
        for k, v in fit(model, args.fine_tune_epochs).items():
            history[k] += v

    fig, ax = plt.subplots(1, 2, figsize=(12, 4))
    for a, k in zip(ax, ("loss", "accuracy")):
        a.plot(history[k], label="train")
        a.plot(history["val_" + k], label="val")
        a.set_title(k)
        a.legend()
    fig.savefig(RESULTS_DIR / f"{args.model}_training_curves.png", dpi=150)
    json.dump(history, open(RESULTS_DIR / f"{args.model}_history.json", "w"), indent=2)
    print(f"Best model saved to {path}")


# ----------------------------- evaluate -----------------------------
def load_trained(name):
    path = MODELS_DIR / f"{name}_best.keras"
    if not path.exists():
        raise FileNotFoundError(f"{path} not found. Run: python main.py train --model {name}")
    return tf.keras.models.load_model(path)


def cmd_evaluate(args):
    model = load_trained(args.model)
    _, _, test_ds = get_datasets(get_data_root(args.data_dir))
    y_true = np.concatenate([y.numpy().ravel() for _, y in test_ds]).astype(int)
    y_prob = model.predict(test_ds, verbose=0).ravel()
    y_pred = (y_prob >= args.threshold).astype(int)

    print(classification_report(y_true, y_pred, target_names=CLASS_NAMES, zero_division=0))
    auc = roc_auc_score(y_true, y_prob)
    print(f"ROC AUC: {auc:.4f}")
    cm = confusion_matrix(y_true, y_pred)
    ConfusionMatrixDisplay(cm, display_labels=CLASS_NAMES).plot(cmap="Blues", values_format="d")
    plt.savefig(RESULTS_DIR / f"{args.model}_confusion_matrix.png", dpi=150, bbox_inches="tight")
    plt.close()
    RocCurveDisplay.from_predictions(y_true, y_prob, name=args.model)
    plt.savefig(RESULTS_DIR / f"{args.model}_roc_curve.png", dpi=150, bbox_inches="tight")
    plt.close()
    json.dump({"threshold": args.threshold, "roc_auc": auc, "confusion_matrix": cm.tolist(),
               "report": classification_report(y_true, y_pred, target_names=CLASS_NAMES,
                                               output_dict=True, zero_division=0)},
              open(RESULTS_DIR / f"{args.model}_metrics.json", "w"), indent=2)
    print(f"Saved plots/metrics to {RESULTS_DIR}")


# ----------------------------- predict + Grad-CAM -----------------------------
def grad_cam(model, img):
    """Grad-CAM heatmap [0,1] for the PNEUMONIA class (flat CNN or nested MobileNetV2)."""
    x = tf.convert_to_tensor(np.expand_dims(img, 0))
    base = next((l for l in reversed(model.layers)
                 if isinstance(l, tf.keras.Model) and l.name != "augmentation"), None)
    if base is None:
        conv = next(l for l in reversed(model.layers) if isinstance(l, layers.Conv2D))
        gm = tf.keras.Model(model.inputs, [conv.output, model.output])
        with tf.GradientTape() as tape:
            conv_out, preds = gm(x)
            loss = preds[:, 0]
        grads = tape.gradient(loss, conv_out)
    else:
        conv = next(l for l in reversed(base.layers) if isinstance(l, layers.Conv2D))
        idx = model.layers.index(base)
        pre, post = model.layers[1:idx], model.layers[idx + 1:]
        bm = tf.keras.Model(base.inputs, [conv.output, base.output])
        with tf.GradientTape() as tape:
            h = x
            for l in pre:
                h = h if "augmentation" in l.name else l(h, training=False)
            conv_out, h = bm(h, training=False)
            tape.watch(conv_out)
            for l in post:
                h = l(h, training=False)
            loss = h[:, 0]
        grads = tape.gradient(loss, conv_out)
    pooled = tf.reduce_mean(grads, axis=(0, 1, 2))
    heat = tf.nn.relu(tf.reduce_sum(conv_out[0] * pooled, axis=-1))
    return (heat / (tf.reduce_max(heat) + 1e-8)).numpy()


def cmd_predict(args):
    model = load_trained(args.model)
    img = tf.keras.utils.img_to_array(
        tf.keras.utils.load_img(args.image, color_mode="rgb", target_size=IMG_SIZE))
    prob = float(model.predict(img[None], verbose=0)[0, 0])
    label = CLASS_NAMES[int(prob >= args.threshold)]
    conf = prob if label == "PNEUMONIA" else 1 - prob
    print(f"Prediction: {label} (confidence {conf:.1%}, P(pneumonia)={prob:.4f})")
    print("NOTE: educational use only - not a medical diagnosis.")

    heat = tf.image.resize(grad_cam(model, img)[..., None], IMG_SIZE).numpy().squeeze()
    overlay = np.clip(img * 0.6 + plt.get_cmap("jet")(heat)[..., :3] * 255 * 0.4, 0, 255)
    fig, ax = plt.subplots(1, 2, figsize=(9, 4.5))
    ax[0].imshow(img.astype("uint8")); ax[0].set_title("Input")
    ax[1].imshow(overlay.astype("uint8")); ax[1].set_title(f"Grad-CAM: {label} ({conf:.1%})")
    for a in ax:
        a.axis("off")
    out = RESULTS_DIR / f"gradcam_{Path(args.image).stem}.png"
    fig.savefig(out, dpi=150, bbox_inches="tight")
    print(f"Grad-CAM saved to {out}")


# ----------------------------- CLI -----------------------------
def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    for name, fn in (("train", cmd_train), ("evaluate", cmd_evaluate), ("predict", cmd_predict)):
        s = sub.add_parser(name)
        s.add_argument("--model", choices=["cnn", "mobilenet"], default="mobilenet")
        s.add_argument("--data-dir", default=None, help="skip Kaggle download, use this folder")
        if name == "predict":
            s.add_argument("image")
        if name != "train":
            s.add_argument("--threshold", type=float, default=0.5)
        else:
            s.add_argument("--epochs", type=int, default=EPOCHS)
            s.add_argument("--fine-tune-epochs", type=int, default=FINE_TUNE_EPOCHS)
            s.add_argument("--no-fine-tune", action="store_true")
        s.set_defaults(fn=fn)
    args = p.parse_args(argv)
    args.fn(args)


